// GenerateOptions controls optional code generation features in dslgen.
type GenerateOptions struct {
	Typed bool // Emit a strongly-typed <FuncName>Actions interface and binder
}

func validateGoIdentifier(name, label string) error {
	if !token.IsIdentifier(name) || token.Lookup(name).IsKeyword() {
		return fmt.Errorf("invalid Go %s identifier %q", label, name)
	}
	return nil
}

// Generate produces gofmt-formatted Go source that reconstructs the DSL
// described by config.
func Generate(config *dslbuilder.DSLConfig, pkgName, funcName string) ([]byte, error) {
	return GenerateWithOptions(config, pkgName, funcName, GenerateOptions{})
}

// GenerateWithOptions produces gofmt-formatted Go source with optional strongly-typed
// action interface generation.
func GenerateWithOptions(config *dslbuilder.DSLConfig, pkgName, funcName string, opts GenerateOptions) ([]byte, error) {
	if config == nil {
		return nil, fmt.Errorf("config cannot be nil")
	}
	if err := validateGoIdentifier(pkgName, "package"); err != nil {
		return nil, err
	}
	if err := validateGoIdentifier(funcName, "function"); err != nil {
		return nil, err
	}

	var b strings.Builder
	cleanName := strings.ReplaceAll(strings.ReplaceAll(config.Name, "\n", " "), "\r", " ")

	fmt.Fprintf(&b, "// Code generated by dslgen from %q grammar. DO NOT EDIT.\n\n", cleanName)
	fmt.Fprintf(&b, "package %s\n\n", pkgName)
	b.WriteString("import (\n\t\"github.com/arturoeanton/go-dsl/pkg/dslbuilder\"\n)\n\n")

	actions := CollectAllActions(config)

	fmt.Fprintf(&b, "// %s builds the %q DSL.\n", funcName, cleanName)
	if len(actions) > 0 {
		b.WriteString("//\n// Register these actions before parsing:\n")
		for _, a := range actions {
			fmt.Fprintf(&b, "//\n//\tdsl.Action(%q, func(args []interface{}) (interface{}, error) { ... })\n", a)
		}
	}
	fmt.Fprintf(&b, "func %s() (*dslbuilder.DSL, error) {\n", funcName)
	fmt.Fprintf(&b, "\tdsl := dslbuilder.New(%q)\n\n", config.Name)

	if config.SignificantNewlines {
		b.WriteString("\tdsl.SetSignificantNewlines(true)\n")
	}
	if config.StartRule != "" {
		fmt.Fprintf(&b, "\tdsl.SetStartRule(%q)\n", config.StartRule)
	}

	// Emit v2 ordered TokenDefs when present; otherwise emit v1 sorted Tokens map.
	if len(config.TokenDefs) > 0 {
		for _, td := range config.TokenDefs {
			switch strings.ToLower(strings.TrimSpace(td.Kind)) {
			case "keyword":
				fmt.Fprintf(&b, "\tif err := dsl.KeywordToken(%q, %q); err != nil {\n\t\treturn nil, err\n\t}\n", td.Name, td.Pattern)
			case "literal":
				fmt.Fprintf(&b, "\tif err := dsl.LiteralToken(%q, %q); err != nil {\n\t\treturn nil, err\n\t}\n", td.Name, td.Pattern)
			case "skip":
				fmt.Fprintf(&b, "\tif err := dsl.SkipToken(%q, %q); err != nil {\n\t\treturn nil, err\n\t}\n", td.Name, td.Pattern)
			case "lookaround":
				fmt.Fprintf(&b, "\tif err := dsl.TokenWithLookaround(%q, %q, %q, %q); err != nil {\n\t\treturn nil, err\n\t}\n", td.Name, td.Pattern, td.Lookahead, td.Lookbehind)
			default:
				fmt.Fprintf(&b, "\tif err := dsl.Token(%q, %q); err != nil {\n\t\treturn nil, err\n\t}\n", td.Name, td.Pattern)
			}
		}
	} else {
		tokenNames := make([]string, 0, len(config.Tokens))
		for name := range config.Tokens {
			tokenNames = append(tokenNames, name)
		}
		sort.Strings(tokenNames)
		for _, name := range tokenNames {
			pattern := config.Tokens[name]
			if kw, ok := keywordFromPattern(pattern); ok {
				fmt.Fprintf(&b, "\tif err := dsl.KeywordToken(%q, %q); err != nil {\n\t\treturn nil, err\n\t}\n", name, kw)
			} else {
				fmt.Fprintf(&b, "\tif err := dsl.Token(%q, %q); err != nil {\n\t\treturn nil, err\n\t}\n", name, pattern)
			}
		}
	}
	b.WriteString("\n")

	// Rules in declaration order.
	for _, rule := range config.Rules {
		switch {
		case rule.ErrorHint != "":
			fmt.Fprintf(&b, "\tdsl.RuleWithError(%q, %#v, %q, %q)\n", rule.Name, rule.Pattern, rule.Action, rule.ErrorHint)
		case rule.Precedence != 0 || rule.Associativity != "":
			fmt.Fprintf(&b, "\tdsl.RuleWithPrecedence(%q, %#v, %q, %d, %q)\n", rule.Name, rule.Pattern, rule.Action, rule.Precedence, rule.Associativity)
		default:
			fmt.Fprintf(&b, "\tdsl.Rule(%q, %#v, %q)\n", rule.Name, rule.Pattern, rule.Action)
		}
	}

	// Pratt expressions in declaration order.
	for _, expr := range config.Expressions {
		fmt.Fprintf(&b, "\n\tdsl.Expression(%q)", expr.Name)
		for _, atom := range expr.Atoms {
			fmt.Fprintf(&b, ".\n\t\tAtom(%q, %q)", atom.Token, atom.Action)
		}
		for _, g := range expr.Groups {
			if g.Action != "" {
				fmt.Fprintf(&b, ".\n\t\tGroupWithAction(%q, %q, %q, %q)", g.Open, g.Inner, g.Close, g.Action)
			} else {
				fmt.Fprintf(&b, ".\n\t\tGroup(%q, %q, %q)", g.Open, g.Inner, g.Close)
			}
		}
		for _, p := range expr.Prefix {
			fmt.Fprintf(&b, ".\n\t\tPrefix(%q, %d, %q)", p.Token, p.Power, p.Action)
		}
		for _, p := range expr.Postfix {
			fmt.Fprintf(&b, ".\n\t\tPostfix(%q, %d, %q)", p.Token, p.Power, p.Action)
		}
		for _, op := range expr.Infix {
			switch strings.ToLower(strings.TrimSpace(op.Assoc)) {
			case "right":
				fmt.Fprintf(&b, ".\n\t\tRight(%q, %d, %q)", op.Token, op.Power, op.Action)
			case "nonassoc", "none":
				fmt.Fprintf(&b, ".\n\t\tInfixNonAssoc(%q, %d, %q)", op.Token, op.Power, op.Action)
			default:
				fmt.Fprintf(&b, ".\n\t\tLeft(%q, %d, %q)", op.Token, op.Power, op.Action)
			}
		}
		for _, c := range expr.Calls {
			fmt.Fprintf(&b, ".\n\t\tCall(%q, %q, %q, %d, %q)", c.Open, c.Close, c.Sep, c.Power, c.Action)
		}
		for _, idx := range expr.Indices {
			fmt.Fprintf(&b, ".\n\t\tIndex(%q, %q, %q, %d, %q)", idx.Open, idx.Inner, idx.Close, idx.Power, idx.Action)
		}
		for _, m := range expr.Members {
			fmt.Fprintf(&b, ".\n\t\tMember(%q, %q, %d, %q)", m.DotToken, m.FieldToken, m.Power, m.Action)
		}
		if expr.Ternary != nil {
			fmt.Fprintf(&b, ".\n\t\tTernary(%q, %q, %d, %q)", expr.Ternary.QuestionToken, expr.Ternary.ColonToken, expr.Ternary.Power, expr.Ternary.Action)
		}
		b.WriteString("\n")
	}

	// Rule formatting layouts in deterministic order.
	if len(config.Layouts) > 0 {
		layoutRules := make([]string, 0, len(config.Layouts))
		for k := range config.Layouts {
			layoutRules = append(layoutRules, k)
		}
		sort.Strings(layoutRules)
		b.WriteString("\n")
		for _, rName := range layoutRules {
			lay := config.Layouts[rName]
			fmt.Fprintf(&b, "\tdsl.SetRuleLayout(%q, dslbuilder.RuleLayout{IndentBlock: %v, NewlineAfter: %#v, NoSpaceBefore: %#v, NoSpaceAfter: %#v})\n",
				rName, lay.IndentBlock, lay.NewlineAfter, lay.NoSpaceBefore, lay.NoSpaceAfter)
		}
	}

	b.WriteString("\n\treturn dsl, nil\n}\n")

	if opts.Typed {
		ifaceName := typedInterfaceName(funcName)
		methodNames := uniqueActionMethodNames(actions)

		fmt.Fprintf(&b, "\n// %s defines strongly-typed semantic action handlers for the %q grammar.\n", ifaceName, cleanName)
		fmt.Fprintf(&b, "type %s interface {\n", ifaceName)
		for _, a := range actions {
			fmt.Fprintf(&b, "\t%s(args []interface{}) (interface{}, error)\n", methodNames[a])
		}
		b.WriteString("}\n\n")

		binderName := funcName + "WithActions"
		fmt.Fprintf(&b, "// %s builds the %q DSL and binds all semantic actions from handler.\n", binderName, cleanName)
		fmt.Fprintf(&b, "func %s(handler %s) (*dslbuilder.DSL, error) {\n", binderName, ifaceName)
		fmt.Fprintf(&b, "\tdsl, err := %s()\n", funcName)
		b.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		if len(actions) > 0 {
			b.WriteString("\tif handler != nil {\n")
			for _, a := range actions {
				fmt.Fprintf(&b, "\t\tdsl.Action(%q, handler.%s)\n", a, methodNames[a])
			}
			b.WriteString("\t}\n")
		}
		b.WriteString("\treturn dsl, nil\n}\n")
	}

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("failed to format generated source: %w", err)
	}
	return src, nil
}

// CollectAllActions returns sorted unique action names across rules and Pratt expressions.
func CollectAllActions(config *dslbuilder.DSLConfig) []string {
	actionSet := map[string]bool{}
	add := func(a string) {
		if a != "" {
			actionSet[a] = true
		}
	}
	for _, r := range config.Rules {
		add(r.Action)
	}
	for _, expr := range config.Expressions {
		for _, a := range expr.Atoms {
			add(a.Action)
		}
		for _, g := range expr.Groups {
			add(g.Action)
		}
		for _, p := range expr.Prefix {
			add(p.Action)
		}
		for _, p := range expr.Postfix {
			add(p.Action)
		}
		for _, op := range expr.Infix {
			add(op.Action)
		}
		for _, c := range expr.Calls {
			add(c.Action)
		}
		for _, idx := range expr.Indices {
			add(idx.Action)
		}
		for _, m := range expr.Members {
			add(m.Action)
		}
		if expr.Ternary != nil {
			add(expr.Ternary.Action)
		}
	}
	actions := make([]string, 0, len(actionSet))
	for a := range actionSet {
		actions = append(actions, a)
	}
	sort.Strings(actions)
	return actions
}

func typedInterfaceName(funcName string) string {
	base := strings.TrimPrefix(funcName, "New")
	if base == "" || !unicode.IsLetter(rune(base[0])) {
		base = funcName
	}
	return exportPascal(base) + "Actions"
}

func uniqueActionMethodNames(actions []string) map[string]string {
	out := make(map[string]string, len(actions))
	used := make(map[string]int, len(actions))
	for _, a := range actions {
		cand := "On" + exportPascal(a)
		if count := used[cand]; count > 0 {
			used[cand] = count + 1
			cand = fmt.Sprintf("%s_%d", cand, count+1)
		} else {
			used[cand] = 1
		}
		out[a] = cand
	}
	return out
}

func exportPascal(raw string) string {
	var parts []string
	var cur strings.Builder
	for _, r := range raw {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			cur.WriteRune(r)
		} else if cur.Len() > 0 {
			parts = append(parts, cur.String())
			cur.Reset()
		}
	}
	if cur.Len() > 0 {
		parts = append(parts, cur.String())
	}
	if len(parts) == 0 {
		return "Action"
	}
	var out strings.Builder
	for _, p := range parts {
		runes := []rune(p)
		runes[0] = unicode.ToUpper(runes[0])
		out.WriteString(string(runes))
	}
	res := out.String()
	if unicode.IsDigit(rune(res[0])) {
		res = "A" + res
	}
	return res
}

func keywordFromPattern(pattern string) (string, bool) {
	if strings.HasPrefix(pattern, `(?i)\b`) && strings.HasSuffix(pattern, `\b`) {
		return strings.TrimSuffix(strings.TrimPrefix(pattern, `(?i)\b`), `\b`), true
	}
	for _, r := range pattern {
		isWord := (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') ||
			(r >= '0' && r <= '9') || r == '_' || r == '-'
		if !isWord {
			return "", false
		}
	}
	hasLetter := strings.IndexFunc(pattern, func(r rune) bool {
		return (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z')
	}) >= 0
	if hasLetter && len(pattern) > 0 {
		return pattern, true
	}
	return "", false
}

// BuildVSCodeExtensionFiles returns the map of relative file paths to file bytes
// for a VS Code / Cursor extension bundle.
func BuildVSCodeExtensionFiles(config *dslbuilder.DSLConfig) (map[string][]byte, error) {
	if config == nil {
		return nil, fmt.Errorf("config cannot be nil")
	}
	slug := SlugifyDSLName(config.Name)
	keywords, literals := extractHighlightLexemes(config)
	files := make(map[string][]byte)

	// 1. package.json
	pkgJSON := map[string]interface{}{
		"name":        slug + "-dsl",
		"displayName": config.Name + " DSL",
		"description": fmt.Sprintf("Syntax highlighting, formatting, and LSP support for the %s DSL (generated by go-dsl)", config.Name),
		"version":     "0.1.0",
		"engines": map[string]string{
			"vscode": "^1.80.0",
		},
		"main": "./extension.js",
		"activationEvents": []string{
			"onLanguage:" + slug,
		},
		"contributes": map[string]interface{}{
			"languages": []map[string]interface{}{
				{
					"id":            slug,
					"aliases":       []string{config.Name + " DSL", slug},
					"extensions":    []string{"." + slug, ".dsl"},
					"configuration": "./language-configuration.json",
				},
			},
			"grammars": []map[string]interface{}{
				{
					"language":  slug,
					"scopeName": "source." + slug,
					"path":      "./syntaxes/" + slug + ".tmLanguage.json",
				},
			},
		},
		"dependencies": map[string]string{
			"vscode-languageclient": "^9.0.1",
		},
	}
	bPkg, err := marshalJSONPretty(pkgJSON)
	if err != nil {
		return nil, err
	}
	files["package.json"] = bPkg

	// 2. language-configuration.json
	langCfg := map[string]interface{}{
		"comments": map[string]interface{}{
			"lineComment":  "//",
			"blockComment": []string{"/*", "*/"},
		},
		"brackets": [][]string{{"{", "}"}, {"[", "]"}, {"(", ")"}},
		"autoClosingPairs": []map[string]string{
			{"open": "{", "close": "}"},
			{"open": "[", "close": "]"},
			{"open": "(", "close": ")"},
			{"open": "\"", "close": "\""},
			{"open": "'", "close": "'"},
		},
		"surroundingPairs": [][]string{{"{", "}"}, {"[", "]"}, {"(", ")"}, {"\"", "\""}, {"'", "'"}},
	}
	bLang, err := marshalJSONPretty(langCfg)
	if err != nil {
		return nil, err
	}
	files["language-configuration.json"] = bLang

	// 3. syntaxes/<slug>.tmLanguage.json
	patterns := []map[string]interface{}{
		{"include": "#comments"},
		{"include": "#strings"},
		{"include": "#numbers"},
	}
	repo := map[string]interface{}{
		"comments": map[string]interface{}{
			"patterns": []map[string]interface{}{
				{"name": "comment.line.double-slash." + slug, "match": `//.*$`},
				{"name": "comment.line.number-sign." + slug, "match": `#.*$`},
				{"name": "comment.block." + slug, "begin": `/\*`, "end": `\*/`},
			},
		},
		"strings": map[string]interface{}{
			"patterns": []map[string]interface{}{
				{"name": "string.quoted.double." + slug, "begin": `"`, "end": `"`, "patterns": []map[string]string{{"name": "constant.character.escape." + slug, "match": `\\.`}}},
				{"name": "string.quoted.single." + slug, "begin": `'`, "end": `'`, "patterns": []map[string]string{{"name": "constant.character.escape." + slug, "match": `\\.`}}},
			},
		},
		"numbers": map[string]interface{}{
			"patterns": []map[string]interface{}{
				{"name": "constant.numeric." + slug, "match": `\b[0-9]+(\.[0-9]+)?\b`},
			},
		},
	}
	if len(keywords) > 0 {
		escaped := make([]string, len(keywords))
		for i, kw := range keywords {
			escaped[i] = regexp.QuoteMeta(kw)
		}
		patterns = append(patterns, map[string]interface{}{"include": "#keywords"})
		repo["keywords"] = map[string]interface{}{
			"patterns": []map[string]interface{}{
				{"name": "keyword.control." + slug, "match": `(?i)\b(` + strings.Join(escaped, "|") + `)\b`},
			},
		}
	}
	if len(literals) > 0 {
		escaped := make([]string, len(literals))
		for i, lit := range literals {
			escaped[i] = regexp.QuoteMeta(lit)
		}
		patterns = append(patterns, map[string]interface{}{"include": "#operators"})
		repo["operators"] = map[string]interface{}{
			"patterns": []map[string]interface{}{
				{"name": "keyword.operator." + slug, "match": `(` + strings.Join(escaped, "|") + `)`},
			},
		}
	}
	tmGrammar := map[string]interface{}{
		"$schema":    "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
		"name":       config.Name,
		"scopeName":  "source." + slug,
		"patterns":   patterns,
		"repository": repo,
	}
	bTM, err := marshalJSONPretty(tmGrammar)
	if err != nil {
		return nil, err
	}
	files["syntaxes/"+slug+".tmLanguage.json"] = bTM

	// 4. extension.js
	extJS := fmt.Sprintf(`// Generated by go-dsl dslgen (-vscode)
const path = require('path');
const vscode = require('vscode');
const { LanguageClient, TransportKind } = require('vscode-languageclient/node');

let client;

function activate(context) {
  const cfg = vscode.workspace.getConfiguration(%q);
  const command = cfg.get('lspPath', 'lsp');
  const grammarPath = cfg.get('grammarPath', path.join(context.extensionPath, 'grammar.yaml'));

  const serverOptions = {
    command,
    args: ['-dsl', grammarPath],
    transport: TransportKind.stdio,
  };

  const clientOptions = {
    documentSelector: [{ scheme: 'file', language: %q }],
  };

  client = new LanguageClient(%q, %q, serverOptions, clientOptions);
  client.start();
}

function deactivate() {
  return client ? client.stop() : undefined;
}

module.exports = { activate, deactivate };
`, slug, slug, slug+"-lsp", config.Name+" Language Server")
	files["extension.js"] = []byte(extJS)

	// 5. grammar.yaml
	if grammarYAML, err := yaml.Marshal(config); err == nil {
		files["grammar.yaml"] = grammarYAML
	}

	return files, nil
}

// GenerateVSCodeExtension writes a VS Code / Cursor extension bundle to outDir.
func GenerateVSCodeExtension(config *dslbuilder.DSLConfig, outDir string) error {
	files, err := BuildVSCodeExtensionFiles(config)
	if err != nil {
		return err
	}
	for rel, data := range files {
		full := filepath.Join(outDir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(full), 0755); err != nil {
			return err
		}
		if err := os.WriteFile(full, data, 0644); err != nil {
			return err
		}
	}
	return nil
}

// GenerateVSCodeExtensionZip builds an in-memory .zip archive of the VS Code / Cursor extension.
func GenerateVSCodeExtensionZip(config *dslbuilder.DSLConfig) ([]byte, error) {
	files, err := BuildVSCodeExtensionFiles(config)
	if err != nil {
		return nil, err
	}
	slug := SlugifyDSLName(config.Name)
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)

	keys := make([]string, 0, len(files))
	for k := range files {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	for _, rel := range keys {
		w, err := zw.Create(slug + "-vscode/" + rel)
		if err != nil {
			return nil, err
		}
		if _, err := w.Write(files[rel]); err != nil {
			return nil, err
		}
	}
	if err := zw.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// SlugifyDSLName converts a DSL name into a safe lowercase hyphenated slug.
func SlugifyDSLName(name string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(strings.TrimSpace(name)) {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') {
			b.WriteRune(r)
		} else if b.Len() > 0 && !strings.HasSuffix(b.String(), "-") {
			b.WriteRune('-')
		}
	}
	res := strings.Trim(b.String(), "-")
	if res == "" {
		return "godsl"
	}
	return res
}

func extractHighlightLexemes(config *dslbuilder.DSLConfig) (keywords []string, literals []string) {
	kwSet := map[string]bool{}
	litSet := map[string]bool{}
	if len(config.TokenDefs) > 0 {
		for _, td := range config.TokenDefs {
			switch strings.ToLower(td.Kind) {
			case "keyword":
				if td.Pattern != "" {
					kwSet[td.Pattern] = true
				}
			case "literal":
				if td.Pattern != "" {
					litSet[td.Pattern] = true
				}
			default:
				if kw, ok := keywordFromPattern(td.Pattern); ok {
					kwSet[kw] = true
				}
			}
		}
	} else {
		for _, pat := range config.Tokens {
			if kw, ok := keywordFromPattern(pat); ok {
				kwSet[kw] = true
			}
		}
	}
	for kw := range kwSet {
		keywords = append(keywords, kw)
	}
	for lit := range litSet {
		literals = append(literals, lit)
	}
	sort.Slice(keywords, func(i, j int) bool {
		if len(keywords[i]) != len(keywords[j]) {
			return len(keywords[i]) > len(keywords[j])
		}
		return keywords[i] < keywords[j]
	})
	sort.Slice(literals, func(i, j int) bool {
		if len(literals[i]) != len(literals[j]) {
			return len(literals[i]) > len(literals[j])
		}
		return literals[i] < literals[j]
	})
	return keywords, literals
}

func marshalJSONPretty(v interface{}) ([]byte, error) {
	data, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}
